/**
 * Response from question generation including quality metrics.
 */
export interface QuestionGenerationResponse {
  /** Generated questions */
  questions: GeneratedQuestion[];

  /** Generation metadata */
  generationId: string;
  generatedAt: string;

  /** Quality summary */
  qualitySummary: {
    averageQuality: number;
    averageDifficulty: number;
    cognitiveDistribution: Record<CognitiveLevel, number>;
    typeDistribution: Record<QuestionType, number>;
    questionsPassedValidation: number;
    questionsFailedValidation: number;
  };

  /** Source information */
  sourceBreakdown: {
    aiGenerated: number;
    curatedBank: number;
    staticFallback: number;
  };

  /** Accommodations applied */
  accommodationsApplied: (keyof LearnerAccommodations)[];

  /** Warnings or notes */
  warnings?: string[];
}

