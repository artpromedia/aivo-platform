/**
 * Learner accommodations aligned with IDEA and Section 504 requirements.
 * These modify question presentation without changing construct measured.
 */
export interface LearnerAccommodations {
  // ── Presentation Accommodations ──
  /** Text-to-speech for question stem and options */
  readAloud?: boolean;
  /** Larger text size (1.25x - 2x normal) */
  largeText?: boolean;
  /** High contrast color scheme */
  highContrast?: boolean;
  /** Visual supports and diagrams for concepts */
  visualSupports?: boolean;
  /** Simplified vocabulary (Flesch-Kincaid grade level reduction) */
  simplifiedLanguage?: boolean;
  /** Bilingual presentation with native language support */
  bilingualSupport?: {
    enabled: boolean;
    primaryLanguage: string; // ISO 639-1 code
  };

  // ── Response Accommodations ──
  /** Extended time multiplier (1.5x, 2x, unlimited) */
  extendedTime?: number | 'unlimited';
  /** Allow speech-to-text for responses */
  speechToText?: boolean;
  /** Allow dictation/scribe input */
  dictation?: boolean;
  /** Allow calculator for math questions */
  calculator?: boolean;

  // ── Setting Accommodations ──
  /** Reduced distractions (simplified UI, fewer elements) */
  reducedDistractions?: boolean;
  /** Frequent breaks between questions */
  frequentBreaks?: boolean;
  /** Break interval in minutes */
  breakIntervalMinutes?: number;

  // ── Format Modifications ──
  /** Reduce number of options (3 instead of 4) */
  reducedOptions?: boolean;
  /** Simplify matching/ordering (fewer items) */
  reducedItems?: boolean;
  /** Chunk content into smaller segments */
  chunkedContent?: boolean;

  // ── Assistive Technology ──
  /** Screen reader compatible formatting */
  screenReaderOptimized?: boolean;
  /** Switch scanning support */
  switchScanning?: boolean;
  /** Eye tracking interface */
  eyeTracking?: boolean;
}

