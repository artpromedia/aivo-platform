/**
 * Question option for multiple-choice type questions.
 */
export interface QuestionOption {
  id: string; // Stable identifier (A, B, C, D)
  text: string;
  isCorrect: boolean;
  /** Explanation of why this is correct/incorrect */
  rationale?: string;
  /** Distractor analysis for incorrect options */
  distractorType?:
    | 'common-misconception'
    | 'partial-understanding'
    | 'careless-error'
    | 'plausible-alternative';
}

/**
 * Matching pair for matching-type questions.
 */
export interface MatchingPair {
  leftItem: string;
  rightItem: string;
  leftId: string;
  rightId: string;
}

/**
 * Rich metadata for question analytics and improvement.
 */
export interface QuestionMetadata {
  // ── Generation Info ──
  source: QuestionSource;
  generatedAt: string; // ISO timestamp
  generationModel?: string; // AI model version
  generationLatencyMs?: number;

  // ── Educational Properties ──
  /** Flesch-Kincaid Grade Level */
  readingLevel: number;
  /** Word count of question stem */
  wordCount: number;
  /** Estimated completion time in seconds */
  estimatedTimeSeconds: number;

  // ── Psychometric Properties ──
  /** IRT difficulty parameter (b) */
  irtDifficulty?: number;
  /** IRT discrimination parameter (a) */
  irtDiscrimination?: number;
  /** Guessing parameter (c) for MC */
  irtGuessing?: number;

  // ── Quality Scores ──
  /** Overall quality score (0-1) */
  qualityScore?: number;
  /** Clarity of stem (0-1) */
  clarityScore?: number;
  /** Distractor quality for MC (0-1) */
  distractorQuality?: number;

  // ── Content Safety ──
  contentRiskLevel: ContentRiskLevel;
  contentFlags?: string[];

  // ── Usage Tracking ──
  timesUsed?: number;
  lastUsed?: string;
  averageResponseTime?: number;
  correctRate?: number;
}

/**
 * Visual element for questions requiring images/diagrams.
 */
export interface QuestionVisual {
  type: 'image' | 'diagram' | 'chart' | 'graph' | 'equation';
  url?: string;
  altText: string;
  /** LaTeX or SVG for rendered content */
  content?: string;
  position: 'before-stem' | 'after-stem' | 'with-options';
}

/**
 * AI-generated assessment question with full educational metadata.
 */
export interface GeneratedQuestion {
  // ── Identification ──
  id: string;
  skillCode: string;

  // ── Question Content ──
  type: QuestionType;
  /** Main question text */
  stem: string;
  /** Additional context or passage */
  passage?: string;
  /** Instructions specific to question type */
  instructions?: string;
  /** Visual elements */
  visuals?: QuestionVisual[];

  // ── Answer Structure ──
  /** Options for MC/matching questions */
  options?: QuestionOption[];
  /** Pairs for matching questions */
  matchingPairs?: MatchingPair[];
  /** Items for ordering questions */
  orderingItems?: string[];
  /** Correct answer(s) */
  correctAnswer: string | string[] | number;
  /** Acceptable alternatives for short-answer */
  acceptableAnswers?: string[];

  // ── Educational Context ──
  /** Explanation of correct answer */
  explanation: string;
  /** Common misconceptions addressed */
  misconceptions?: string[];
  /** Hints for scaffolded support */
  hints?: string[];
  /** Standards aligned to this question */
  standardsAlignment: string[];

  // ── Properties ──
  /** Difficulty on 0-1 scale */
  difficulty: number;
  /** Bloom's taxonomy level */
  cognitiveLevel: CognitiveLevel;

  // ── Metadata ──
  metadata: QuestionMetadata;
}

