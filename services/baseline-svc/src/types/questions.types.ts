/**
 * Question-level analytics for performance tracking.
 */
export interface QuestionAnalytics {
  questionId: string;
  skillCode: string;

  // ── Usage Metrics ──
  totalAttempts: number;
  uniqueLearners: number;

  // ── Performance Metrics ──
  correctRate: number; // Proportion correct
  averageLatencyMs: number;
  medianLatencyMs: number;

  // ── Psychometric Metrics ──
  /** Point-biserial correlation */
  discriminationIndex: number;
  /** IRT difficulty estimate */
  difficultyEstimate: number;
  /** Item-total correlation */
  itemTotalCorrelation: number;

  // ── Distractor Analysis (MC only) ──
  optionDistribution?: Record<string, number>;
  distractorEffectiveness?: Record<string, number>;

  // ── Quality Indicators ──
  skipRate: number;
  timeoutRate: number;
  feedbackScores?: {
    average: number;
    count: number;
  };

  // ── Time Period ──
  periodStart: string;
  periodEnd: string;
}

