/**
 * Supported question types following best practices in educational assessment.
 * Each type maps to specific cognitive demands and response patterns.
 */
export type QuestionType =
  | 'multiple-choice' // 4-option MC, single correct answer
  | 'multiple-select' // Multi-correct MC (check all that apply)
  | 'short-answer' // Brief text response (1-3 sentences)
  | 'matching' // Pair items from two lists
  | 'ordering' // Arrange items in correct sequence
  | 'fill-blank' // Complete sentence with missing word(s)
  | 'true-false' // Binary choice
  | 'constructed-response'; // Extended written response

/**
 * Bloom's Taxonomy cognitive levels for question classification.
 * Higher levels indicate deeper cognitive processing required.
 */
export type CognitiveLevel =
  | 'remember' // Recall facts, terms, basic concepts (Level 1)
  | 'understand' // Explain ideas, interpret meaning (Level 2)
  | 'apply' // Use information in new situations (Level 3)
  | 'analyze' // Draw connections, identify patterns (Level 4)
  | 'evaluate' // Justify, critique, make judgments (Level 5)
  | 'create'; // Produce original work, design solutions (Level 6)

/**
 * Difficulty tiers aligned with grade-level expectations.
 */
export type DifficultyLevel = 'foundational' | 'grade-level' | 'challenging';

/**
 * Risk levels for content validation.
 */
export type ContentRiskLevel = 'safe' | 'review' | 'flagged' | 'blocked';

/**
 * Question source for provenance tracking.
 */
export type QuestionSource =
  | 'ai-generated' // Generated by AI during assessment
  | 'curated-bank' // From reviewed question bank
  | 'static-fallback' // Last-resort static questions
  | 'teacher-created' // Teacher-authored questions
  | 'imported'; // Imported from external source

