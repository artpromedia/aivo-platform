  periodStart: string;
  periodEnd: string;

  // ── Generation Metrics ──
  totalRequests: number;
  successfulGenerations: number;
  failedGenerations: number;
  averageLatencyMs: number;
  p95LatencyMs: number;

  // ── Quality Metrics ──
