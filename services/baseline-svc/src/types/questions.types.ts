/**
 * Question Generator Service Interface
 */
export interface IQuestionGeneratorService {
  /**
   * Generate questions using AI with fallback chain.
   */
  generateQuestions(request: QuestionGenerationRequest): Promise<QuestionGenerationResponse>;

  /**
   * Validate a question against educational standards.
   */
  validateQuestion(question: GeneratedQuestion): Promise<QuestionValidationResult>;

  /**
   * Get questions from curated bank.
   */
  getFromQuestionBank(query: QuestionBankQuery): Promise<GeneratedQuestion[]>;

  /**
   * Invalidate cached questions for regeneration.
   */
  invalidateCache(key: string): Promise<void>;
}

/**
 * Question Analytics Service Interface
 */
export interface IQuestionAnalyticsService {
  /**
   * Record a question response for analytics.
   */
  recordResponse(params: {
    questionId: string;
    learnerId: string;
    isCorrect: boolean;
    latencyMs: number;
    selectedOption?: string;
    source: QuestionSource;
  }): Promise<void>;

  /**
   * Get analytics for a specific question.
   */
  getQuestionAnalytics(questionId: string): Promise<QuestionAnalytics | null>;

  /**
   * Get AI generation analytics for monitoring.
   */
  getGenerationAnalytics(startDate: string, endDate: string): Promise<AIGenerationAnalytics>;

  /**
   * Get questions that need review based on performance.
   */
  getQuestionsNeedingReview(): Promise<{ questionId: string; reason: string }[]>;
}

