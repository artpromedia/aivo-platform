/**
 * Previous response data for adaptive question generation.
 * Enables AI to adjust difficulty and focus based on learner performance.
 */
export interface PreviousResponse {
  skillCode: string;
  questionType: QuestionType;
  wasCorrect: boolean;
  latencyMs: number;
  difficulty: number;
  cognitiveLevel: CognitiveLevel;
}

/**
 * Standards alignment information for curriculum mapping.
 */
export interface StandardsContext {
  /** Common Core State Standards codes */
  ccssStandards?: string[];
  /** Next Generation Science Standards */
  ngssStandards?: string[];
  /** State-specific standards codes */
  stateStandards?: {
    state: string;
    codes: string[];
  };
}

/**
 * Request payload for AI question generation.
 * Provides full context for generating educationally valid questions.
 */
export interface QuestionGenerationRequest {
  // ── Identification ──
  tenantId: string;
  learnerId: string;
  assessmentSessionId?: string;

  // ── Academic Context ──
  subject: BaselineDomain;
  gradeLevel: number; // Numeric grade (K=0, 1-12)
  gradeBand: GradeBand;
  topicArea: string; // Specific topic within domain
  skillCodes: string[]; // Skill codes to assess

  // ── Question Parameters ──
  difficultyLevel: DifficultyLevel;
  targetDifficulty?: number; // 0-1 scale for adaptive
  questionCount: number;
  questionTypes: QuestionType[];

  // ── Adaptive Context ──
  previousResponses?: PreviousResponse[];
  currentAbilityEstimate?: number; // IRT theta estimate

  // ── Accommodations ──
  accommodations?: LearnerAccommodations;

  // ── Standards ──
  standardsContext?: StandardsContext;

  // ── Generation Preferences ──
  preferences?: {
    /** Avoid questions similar to recent ones */
    avoidSimilar?: boolean;
    /** Prefer practical/real-world contexts */
    realWorldContexts?: boolean;
    /** Include visual elements when applicable */
    includeVisuals?: boolean;
    /** Cultural context preferences */
    culturalContext?: string;
  };
}

